const TABLES: Record<string, Table> = { en, de, fr, it, es, nl, pl, ro };

/** Languages with their own labels; any other tag falls back to English. */
export const RENDER_LANGUAGES = Object.keys(TABLES);

/** A language the renderers have labels for. Any other BCP 47 tag is accepted too and gets English labels. */
export type RenderLanguage = 'en' | 'de' | 'fr' | 'it' | 'es' | 'nl' | 'pl' | 'ro';

/** Reduces a BCP 47 tag to something safe to put in a `lang` attribute; anything odd becomes `en`. */
export function safeLang(lang: string | undefined): string {
  return lang && /^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8}){0,3}$/.test(lang) ? lang : 'en';
}

/** Returns the label function for a language tag such as `de` or `fr-CH`. */
export function labelsFor(lang: string | undefined): (key: LabelKey) => string {
  const table = TABLES[safeLang(lang).slice(0, 2).toLowerCase()] ?? en;
  return (key) => table[key];
}

/** Whether a label exists for `key`, for codes that come from the invoice (`catS`, `pm30`). */
export function isLabelKey(key: string): key is LabelKey {
  return Object.hasOwn(en, key);
}
